#!/usr/bin/env python3
"""Regenerates src/lib/branding/brandTokens.ts from the hard-coded Tailwind color
classes (e.g. bg-[#0B57D0]) found in src/**/*.tsx. Run from the project root
after adding new hard-coded colors:  python3 scripts/gen-brand-tokens.py"""
import glob, re, json

pat = re.compile(
    r'(?<![\w\[\]:/-])((?:[a-z0-9\-\[\]=\.\(\)]+:)*)'
    r'(bg|text|border|ring|from|to|via|accent)-\[#([0-9A-Fa-f]{6})\](?:/(\d+))?'
)
seen = {}
for f in sorted(glob.glob('src/**/*.tsx', recursive=True)):
    for m in pat.finditer(open(f, encoding='utf8').read()):
        raw = m.group(0)
        variants = m.group(1)[:-1] if m.group(1) else ''
        seen[raw] = [raw, variants, m.group(2), m.group(3).upper(), m.group(4) or '']

rows = json.dumps(sorted(seen.values()), indent=1)
open('src/lib/branding/brandTokens.ts', 'w').write(
    '// AUTO-GENERATED by scripts/gen-brand-tokens.py - do not edit by hand.\n'
    '/** [rawClass, variants, utility, HEX, opacity] */\n'
    'export const BRAND_TOKENS: ReadonlyArray<readonly [string, string, string, string, string]> = '
    + rows + ';\n'
)
print(len(seen), 'tokens written')
